import katex from './vendor/katex-0.19.1/katex.mjs';

const MAX_FORMULA_LENGTH = 2048;

// Create fresh settings (including macros) per formula. Never retain definitions
// from one paper's metadata while rendering another paper.
function settings(output = 'htmlAndMathml') {
  return {
    output, displayMode: false, throwOnError: true, trust: false,
    strict: 'error', maxExpand: 100, maxSize: 10,
    macros: { '\\textlangle': '\\langle', '\\textrangle': '\\rangle' },
  };
}

function escaped(text, index) {
  let slashes = 0;
  while (index > 0 && text[--index] === '\\') slashes++;
  return slashes % 2 === 1;
}

function singleDollar(text, index) {
  return text[index] === '$' && text[index - 1] !== '$' &&
    text[index + 1] !== '$' && !escaped(text, index);
}

// Only inline, explicitly delimited math is recognized. Whitespace immediately
// inside dollar delimiters is excluded to keep ordinary prices literal.
export function titleSegments(title) {
  const text = String(title ?? '');
  const parts = [];
  let plainStart = 0;
  for (let start = 0; start < text.length; start++) {
    const dollar = singleDollar(text, start) && !/\s/.test(text[start + 1] ?? ' ');
    const paren = text.startsWith('\\(', start) && !escaped(text, start);
    if (!dollar && !paren) continue;
    const width = dollar ? 1 : 2;
    let end = start + width;
    for (; end < text.length && text[end] !== '\n' && text[end] !== '\r'; end++) {
      if (dollar ? singleDollar(text, end) : text.startsWith('\\)', end) && !escaped(text, end)) break;
    }
    if (end >= text.length || /[\r\n]/.test(text[end]) || end === start + width ||
        (dollar && /\s/.test(text[end - 1]))) continue;
    if (start > plainStart) parts.push({ type: 'text', text: text.slice(plainStart, start) });
    parts.push({ type: 'math', text: text.slice(start + width, end), raw: text.slice(start, end + width) });
    start = end + width - 1;
    plainStart = start + 1;
  }
  if (plainStart < text.length) parts.push({ type: 'text', text: text.slice(plainStart) });
  return parts;
}

function checkLength(formula) {
  if (formula.length > MAX_FORMULA_LENGTH) throw new Error('Title formula exceeds rendering limit');
}

// renderText owns highlighting in plain text. Formula DOM is left intact so
// highlighting cannot split KaTeX's visual representation or accessible MathML.
export function renderTitle(container, title, renderText = (node, text) => {
  node.appendChild(node.ownerDocument.createTextNode(text));
}) {
  container.replaceChildren();
  // Highlighters may replace their target's children. Give each text segment
  // its own target so later text cannot erase an earlier formula or segment.
  const appendText = text => {
    const span = container.ownerDocument.createElement('span');
    renderText(span, text);
    container.appendChild(span);
  };
  for (const part of titleSegments(title)) {
    if (part.type === 'text') {
      appendText(part.text);
      continue;
    }
    try {
      checkLength(part.text);
      const span = container.ownerDocument.createElement('span');
      span.className = 'title-math';
      katex.render(part.text, span, settings());
      container.appendChild(span);
    } catch {
      appendText(part.raw);
    }
  }
}

function mathText(formula) {
  checkLength(formula);
  // This string is generated by KaTeX and used only as a search string. It is
  // never assigned to innerHTML. Remove TeX annotations before extracting text.
  return katex.renderToString(formula, settings('mathml'))
    .replace(/<annotation\b[^>]*>[\s\S]*?<\/annotation>/g, '')
    .replace(/<[^>]*>/g, '')
    .replace(/&(#x[0-9a-f]+|#\d+|amp|lt|gt|quot|apos|nbsp);/gi, (entity, name) => {
      if (name[0] === '#') {
        const value = name[1].toLowerCase() === 'x' ? parseInt(name.slice(2), 16) : parseInt(name.slice(1), 10);
        return value <= 0x10ffff ? String.fromCodePoint(value) : entity;
      }
      return { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' }[name.toLowerCase()];
    });
}

export function titleSearchText(title) {
  return titleSegments(title).map(part => {
    if (part.type === 'text') return part.text;
    try { return mathText(part.text); } catch { return part.raw; }
  }).join('');
}
